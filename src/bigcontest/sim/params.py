def mult_table() -> np.ndarray:
    """페르소나 × 상태 × 업종 결제 배율 배열 (7 × 3 × 7)."""
    out = np.ones((len(PERSONAS), 3, len(CATS)))
    for i, p in enumerate(PERSONAS.values()):
        for s in (A, R, W):
            for k, c in enumerate(CATS):
                out[i, s, k] = p.mult.get(s, {}).get(c, 1.0)
    return out


def out_table() -> np.ndarray:
    return np.array([p.out_prob for p in PERSONAS.values()])


def check_personas() -> None:
    for p in PERSONAS.values():
        for M in (p.base, p.trigger):
            if M is None:
                continue
